package model.bean;

public class Cliente {
    private Integer clicod;
    private String clinome;
    private String clirg;
    private String clicpf;    
    private String cliend;
    private String clifone;
    private String procurar;
    
    public Cliente() {
    }
    
    public Integer getClicod() {
        return clicod;
    }

    public void setClicod(Integer clicod) {
        this.clicod = clicod;
    }

    public String getClinome() {
        return clinome;
    }

    public void setClinome(String clinome) {
        this.clinome = clinome;
    }

    public String getClirg() {
        return clirg;
    }

    public void setClirg(String clirg) {
        this.clirg = clirg;
    }

    public String getClicpf() {
        return clicpf;
    }

    public void setClicpf(String clicpf) {
        this.clicpf = clicpf;
    }

    public String getCliend() {
        return cliend;
    }

    public void setCliend(String cliend) {
        this.cliend = cliend;
    }

    public String getClifone() {
        return clifone;
    }

    public void setClifone(String clifone) {
        this.clifone = clifone;
    }

    public String getProcurar() {
        return procurar;
    }

    public void setProcurar(String procurar) {
        this.procurar = procurar;
    }
        
}
