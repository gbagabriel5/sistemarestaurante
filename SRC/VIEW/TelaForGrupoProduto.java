    private void btsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btsalvarActionPerformed
        if(txtdesc.getText().equals("")){
            txtdesc.requestFocus();
            JOptionPane.showMessageDialog(null, "Campo Descricao Obrigatorio ","Aviso ",JOptionPane.WARNING_MESSAGE);
            return;   
        }         
        
       grp.setGrpdesc(txtdesc.getText());              
       grpdao.salvarTipo(grp);
       
       preencherTabela("select * from grupoproduto");
        
       txtdesc.setEnabled(false);        
       bteditar.setEnabled(false);
       btexcluir.setEnabled(false);
       btsalvar.setEnabled(false);
       btnovo.setEnabled(true);        
       txtdesc.setText("");            
    }//GEN-LAST:event_btsalvarActionPerformed

    private void bteditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bteditarActionPerformed
        if(txtdesc.getText().equals("")){
            txtdesc.requestFocus();
            JOptionPane.showMessageDialog(null, "Campo Descricao ","Aviso ",JOptionPane.WARNING_MESSAGE);
            return;   
        }                   
        String cod=""+tabelaProduto.getValueAt(tabelaProduto.getSelectedRow(),0); 
        grp.setGrpcod(Integer.parseInt(cod));
        grp.setGrpdesc(txtdesc.getText());              
        grpdao.updateTipo(grp);
        
        preencherTabela("select * from grupoproduto");

        txtdesc.setEnabled(false);                
        
        bteditar.setEnabled(false);
        btexcluir.setEnabled(false);
        btsalvar.setEnabled(false);
        btnovo.setEnabled(true);        
        txtdesc.setText("");       
        
        preencherTabela("select * from grupoproduto");
    }//GEN-LAST:event_bteditarActionPerformed
        
    private void btexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btexcluirActionPerformed
       int opcao=JOptionPane.showConfirmDialog(null, "VOCÊ DESEJA REALMENTE EXCLUIR ?");
       switch(opcao){
           case 0:         
                String cod=""+tabelaProduto.getValueAt(tabelaProduto.getSelectedRow(),0); 
                grp.setGrpcod(Integer.parseInt(cod));
                grpdao.excluirTipo(grp);            
                txtdesc.setText("");                       
                preencherTabela("select * from grupoproduto");
            break;                    
        }
    }//GEN-LAST:event_btexcluirActionPerformed

    private void tabelaProdutoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaProdutoMouseClicked
        btnovo.setEnabled(false);
        btsalvar.setEnabled(false);
        bteditar.setEnabled(true);
        btexcluir.setEnabled(true);
        txtdesc.setEnabled(true);                
        if(flag==1){
            conecta.conexao();            
            String cod=""+tabelaProduto.getValueAt(tabelaProduto.getSelectedRow(),0);        
            grp.setProcurar(cod);
            GrupoProduto p= grpdao.ProcurarTipo(grp);
            txtdesc.setText(p.getGrpdesc());        
        }
        bteditar.setEnabled(true);        
    }//GEN-LAST:event_tabelaProdutoMouseClicked

