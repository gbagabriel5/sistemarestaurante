    private void jMenuItem1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem1ActionPerformed
        conecta.conexao();   
        try {                                   
            conecta.executaSql("select *from caixa");
            conecta.rs.last();            
           
            if(conecta.rs.getString("cxstatus").equals("ABERTO") ){
            tm.setVisible(true);
//            tm.setAlwaysOnTop(true);
            tm.setResizable(false);            
            }else{
                JOptionPane.showMessageDialog(rootPane,"O caixa esta fechado, abra o caixa para continuar.");                
            }
                                
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(rootPane,"O caixa esta fechado, abra o caixa para continuar."+ex);            
            
        }
        
    }//GEN-LAST:event_jMenuItem1ActionPerformed

