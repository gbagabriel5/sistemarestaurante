    private void TabelaUsuarioMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TabelaUsuarioMouseClicked
       // quando clicar na informação da tabela ira aparacer as informaçoes nos campos a cima!
            String usunome =""+TabelaUsuario.getValueAt(TabelaUsuario.getSelectedRow(), 1);
            conex.conexao();
            conex.executaSql("SELECT *FROM usuario WHERE usunome='"+usunome+"'");
        try {
            conex.rs.first();
            
            txtID.setText(String.valueOf(conex.rs.getInt("usucodigo")));
            txtUsuario.setText(conex.rs.getString("usunome"));
            txtsenhaUsuario.setText(conex.rs.getString("ususenha"));
            txtsenhaConfirSenha.setText(conex.rs.getString("ususenha"));
            txtComboBoxTipo.setSelectedItem(conex.rs.getString("usutipo"));
        } catch (SQLException ex) {
             JOptionPane.showMessageDialog(null, "Erro de Mouse Clicked" +ex);
        }
            conex.desconecta();
            btnNovo.setEnabled(false);
            btnAlterar.setEnabled(true);
            btnExcluir.setEnabled(true);
            btnCancelar.setEnabled(true);
            btnSalvar.setEnabled(false);
            
            txtID.setEnabled(false);
            txtUsuario.setEnabled(false);
            txtsenhaUsuario.setEnabled(false);
            txtsenhaConfirSenha.setEnabled(false);
            txtComboBoxTipo.setEnabled(false);
    }//GEN-LAST:event_TabelaUsuarioMouseClicked

