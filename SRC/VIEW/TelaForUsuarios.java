    public void preencherTabela(String sql){
    ArrayList dados = new ArrayList();
    String [] colunas = new String []{"ID","Usuario","Tipo"};
    conex.conexao();
    conex.executaSql(sql);
     try{
         conex.rs.first();
         do{
            dados.add(new Object[]{conex.rs.getInt("usucodigo"),conex.rs.getString("usunome"),conex.rs.getString("usutipo")});
         }while(conex.rs.next());
     }catch(SQLException ex){
        JOptionPane.showMessageDialog(rootPane, "Busque por um Usuario existente na Tabela!");
    }
    Tabela modelo = new Tabela(dados, colunas);
    
    TabelaUsuario.setModel(modelo);//mostrando a coluna e o tamanho da coluna que e 23.
    TabelaUsuario.getColumnModel().getColumn(0).setPreferredWidth(40);//primeiro registro que do ID.
    TabelaUsuario.getColumnModel().getColumn(0).setResizable(false);//aqui o usuario nao vai poder redimencionar a tabela, aumentar ou diminuir
    
    TabelaUsuario.getColumnModel().getColumn(1).setPreferredWidth(155);
    TabelaUsuario.getColumnModel().getColumn(1).setResizable(false);
    
    TabelaUsuario.getColumnModel().getColumn(2).setPreferredWidth(155);
    TabelaUsuario.getColumnModel().getColumn(2).setResizable(false);
    
    TabelaUsuario.getTableHeader().setReorderingAllowed(false);//nao vai poder reoodernar o cabeçalho.
    TabelaUsuario.setAutoResizeMode(TabelaUsuario.AUTO_RESIZE_OFF);//nao vai poder ser redimensionada.
    TabelaUsuario.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
    
    conex.desconecta();
   }
    
