    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        
        if(txtUsuario.getText().isEmpty()){//se o nome tiver vazio ...
            JOptionPane.showMessageDialog(null, "Preencha o campo Usuario!");
            txtUsuario.requestFocus();// voltar para o campo
        }else if(txtsenhaUsuario.getText().isEmpty()){
             JOptionPane.showMessageDialog(null, "Preencha o campo Senha!");
            txtsenhaUsuario.requestFocus();
        }else if(txtsenhaConfirSenha.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Preencha o campo Confirmar Senha!");
            txtsenhaConfirSenha.requestFocus();
                  
           //else para so salvar se a senha e o confirmar senha for iguais. pega a senha compara com a confirma...
        }else 
            
        if(txtsenhaUsuario.getText().equals(txtsenhaConfirSenha.getText())){
            
            if(flag==1){// se for igual a 1 ele vai salvar.. metode de salvar
        mod.setUsuUsuario(txtUsuario.getText());
        mod.setUsuTipo((String)txtComboBoxTipo.getSelectedItem());
        mod.setUsuSenha(txtsenhaUsuario.getText());
        dao.SalvarUsuario(mod);
        preencherTabela("SELECT *FROM usuario ORDER BY usunome");
        
        txtID.setText("");
        txtUsuario.setText("");
        txtsenhaUsuario.setText("");
        txtsenhaConfirSenha.setText("");
        txtUsuario.setEnabled(false);
        txtComboBoxTipo.setEnabled(false);
        txtsenhaUsuario.setEnabled(false);
        txtsenhaConfirSenha.setEnabled(false);
        btnSalvar.setEnabled(false);
        btnNovo.setEnabled(true);
        txtID.setText("");
        btnAlterar.setEnabled(true);
        btnCancelar.setEnabled(false);
        
        
        
        }else{// se nao ele altara... metodo de alterar
        mod.setUsuCodigo(Integer.parseInt(txtID.getText()));
        mod.setUsuUsuario(txtUsuario.getText());
        mod.setUsuTipo((String)txtComboBoxTipo.getSelectedItem());
        mod.setUsuSenha(txtsenhaUsuario.getText());
        dao.AlterarUsuario(mod);
        preencherTabela("SELECT *FROM usuario ORDER BY usunome");
        
        txtUsuario.setText("");
        txtsenhaUsuario.setText("");
        txtsenhaConfirSenha.setText("");
        txtUsuario.setEnabled(false);
        txtComboBoxTipo.setEnabled(false);
        txtsenhaUsuario.setEnabled(false);
        txtsenhaConfirSenha.setEnabled(false);
        btnNovo.setEnabled(true);
        txtID.setText("");
        btnAlterar.setEnabled(false);
        btnCancelar.setEnabled(false);                
        }
        }else{//else para dizer que as senhas nao são iguais...
            JOptionPane.showMessageDialog(rootPane, "As senha não correspondem!");            
        }                    
    }//GEN-LAST:event_btnSalvarActionPerformed

