    private void btacessarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btacessarActionPerformed
        try {
                con.executaSql("SELECT *FROM usuario WHERE usunome='"+txtLogin.getText()+"'");
                con.rs.first();
                if(con.rs.getString("ususenha").equals(txtSenha.getText())){
                    TelaInicial tela = new TelaInicial();
                    tela.setVisible(true);             
                    tela.Recebendo(txtLogin.getText());
//                    play("som");
                    dispose();                    
            }else{
                    JOptionPane.showMessageDialog(rootPane, "Usuario ou Senha invalidos!");
                }
            } catch (SQLException ex) {
                 JOptionPane.showMessageDialog(rootPane, "Usuario ou Senha invalidos!");
        }        
    }//GEN-LAST:event_btacessarActionPerformed
