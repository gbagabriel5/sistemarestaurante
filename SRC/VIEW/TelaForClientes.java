    private void btsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btsalvarActionPerformed
        if(txtnome.getText().equals("")){
            txtnome.requestFocus();
            JOptionPane.showMessageDialog(null, "Preencha o campo NOME!","Aviso ",JOptionPane.WARNING_MESSAGE);
            return;               
        }
         if(txtend.getText().equals("")){
            txtend.requestFocus();
            JOptionPane.showMessageDialog(null, "Preencha o campo ENDEREÇO!","Aviso ",JOptionPane.WARNING_MESSAGE);
            return;   
        }          
          if(txtrg.getText().equals("       - ")){
            txtrg.requestFocus();
            JOptionPane.showMessageDialog(null, "Preencha o campo RG!","Aviso ",JOptionPane.WARNING_MESSAGE);
            return;   
        }
            if(txttel.getText().equals("(  )     -    ")){
            txttel.requestFocus();
            JOptionPane.showMessageDialog(null, "Preencha o campo TELEFONE!","Aviso ",JOptionPane.WARNING_MESSAGE);
            return;   
        }
        cliente.setClinome(txtnome.getText());
        cliente.setClirg(txtrg.getText());
                
        String cpf = txtcpf.getText();
        CPF pf = new CPF(cpf);
        if(pf.isCPF()){
            cliente.setClicpf(txtcpf.getText());            
        }else{
            txtcpf.requestFocus();
            JOptionPane.showMessageDialog(rootPane,"CPF Inválido!");                        
            return;   
        }                
        cliente.setCliend(txtend.getText());
        cliente.setClifone(txttel.getText());                
            
        clientedao.salvarCliente(cliente);
        
        preencherTabela("select * from cliente order by clinome");
        txtnome.setEnabled(false);
        txtrg.setEnabled(false);        
        txtcpf.setEnabled(false);
        txtend.setEnabled(false);                       
        txttel.setEnabled(false);
        
        bteditar.setEnabled(false);
        btexcluir.setEnabled(false);
        btsalvar.setEnabled(false);
        btnovo.setEnabled(true);
        
        txtnome.setText("");
        txtrg.setText("");
        txtcpf.setText("");        
        txtend.setText("");        
        txttel.setText("");
    }//GEN-LAST:event_btsalvarActionPerformed

