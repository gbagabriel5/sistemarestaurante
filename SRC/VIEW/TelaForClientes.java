        tabelabuscarCliente.getTableHeader().setReorderingAllowed(false);
        tabelabuscarCliente.setAutoResizeMode(tabelabuscarCliente.AUTO_RESIZE_OFF);
        tabelabuscarCliente.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
       
