    private void txtendKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtendKeyPressed
        if(evt.getKeyCode()==evt.VK_ENTER){
            if(bteditar.isEnabled()==false){
                if(txtnome.getText().equals("")){
                    txtnome.requestFocus();
                    JOptionPane.showMessageDialog(null, "Preencha o campo NOME!","Aviso ",JOptionPane.WARNING_MESSAGE);
                    return;   
                }
            if(txtend.getText().equals("")){
                txtend.requestFocus();
                JOptionPane.showMessageDialog(null, "Preencha o campo ENDEREÇO!","Aviso ",JOptionPane.WARNING_MESSAGE);
                return;   
            }                   
            if(txtfone.getText().equals("(  )     -    ")){
                txtfone.requestFocus();
                JOptionPane.showMessageDialog(null, "Preencha o campo FONE!","Aviso ",JOptionPane.WARNING_MESSAGE);
                return;          
            }
            if(txtcep.getText().equals("")){
                txtcep.requestFocus();
                JOptionPane.showMessageDialog(null, "Preencha o campo SALARIO!","Aviso ",JOptionPane.WARNING_MESSAGE);
                return;   
            }
        
            forn.setFornome(txtnome.getText());       
            String cnpj = txtcnpj.getText();
            CNPJ pj = new CNPJ(cnpj);
            if(pj.isCNPJ()){
                forn.setForcnpj(txtcnpj.getText());            
            }else{
                txtcnpj.requestFocus();
                JOptionPane.showMessageDialog(rootPane,"CNPJ Inválido!");                        
                return;   
            }                             
            forn.setForcep(txtcep.getText()); 
            forn.setForend(txtend.getText());
            forn.setForfone(txtfone.getText());              
            forndao.salvarFornecedor(forn);
       
            preencherTabela("select * from fornecedor order by fornome");
        
            txtnome.setEnabled(false);        
            txtcnpj.setEnabled(false);                
            txtend.setEnabled(false);                
            txtfone.setEnabled(false);
            txtcep.setEnabled(false);        
        
            bteditar.setEnabled(false);
            btexcluir.setEnabled(false);
            btsalvar.setEnabled(false);
            btnovo.setEnabled(true);
        
            txtnome.setText("");        
            txtcnpj.setText("");        
            txtend.setText("");                
            txtfone.setText("");
            txtcep.setText("");
        }else if(bteditar.isEnabled()==true){
            if(txtnome.getText().equals("")){
                txtnome.requestFocus();
                JOptionPane.showMessageDialog(null, "Preencha o campo NOME!","Aviso ",JOptionPane.WARNING_MESSAGE);
                return;   
            }                    
            if(txtend.getText().equals("")){
                txtend.requestFocus();
                JOptionPane.showMessageDialog(null, "Preencha o campo ENDEREÇO!","Aviso ",JOptionPane.WARNING_MESSAGE);
                return;   
            }                   
            if(txtfone.getText().equals("(  )     -    ")){
                txtfone.requestFocus();
                JOptionPane.showMessageDialog(null, "Preencha o campo FONE!","Aviso ",JOptionPane.WARNING_MESSAGE);
                return;          
            }
            if(txtcep.getText().equals("")){
                txtcep.requestFocus();
                JOptionPane.showMessageDialog(null, "Preencha o campo SALARIO!","Aviso ",JOptionPane.WARNING_MESSAGE);
                return;   
            }
            
            forn.setForcod(Integer.parseInt(cod));
            forn.setFornome(txtnome.getText());       
            String cnpj = txtcnpj.getText();
            CNPJ pj = new CNPJ(cnpj);
            if(pj.isCNPJ()){
                forn.setForcnpj(txtcnpj.getText());            
            }else{
                txtcnpj.requestFocus();
                JOptionPane.showMessageDialog(rootPane,"CNPJ Inválido!");                        
                return;   
            }                      
            forn.setForcep(txtcep.getText());       
            forn.setForend(txtend.getText());
            forn.setForfone(txtfone.getText());       
            forndao.updateFor(forn);
        
            preencherTabela("select * from fornecedor order by fornome");

            txtnome.setEnabled(false);
            txtcnpj.setEnabled(false);
            txtend.setEnabled(false);                
            txtfone.setEnabled(false);
            txtcep.setEnabled(false);        
        
            bteditar.setEnabled(false);
            btexcluir.setEnabled(false);
            btsalvar.setEnabled(false);
            btnovo.setEnabled(true);
                
            txtnome.setText("");        
            txtcnpj.setText("");        
            txtend.setText("");                
            txtfone.setText("");
            txtcep.setText("");
            preencherTabela("select * from fornecedor order by fornome");
        }
    }
    }//GEN-LAST:event_txtendKeyPressed

