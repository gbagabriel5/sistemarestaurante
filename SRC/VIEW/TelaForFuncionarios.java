    public void preencherJCombo(){
        conecta.conexao();
        conecta.executaSQL("select *from departamento order by depdesc");
        try {
            conecta.rs.first();
            comboDepartamento.removeAllItems();
            do{
               comboDepartamento.addItem(conecta.rs.getString("depdesc"));
            }while(conecta.rs.next());
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(rootPane, "erro ao preecher combo\n"+ex);
        }
    }
